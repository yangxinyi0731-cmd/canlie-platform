export type IconName = keyof typeof SVG_PATHS | string;

/**
 * UTF-8 安全 base64 编码（小程序运行时无 btoa，手写实现）
 * 注意：真机 <image> 不支持 URL 编码的 svg data URI（data:image/svg+xml;utf8,...），
 * 只支持 base64 形式（data:image/svg+xml;base64,...），开发者工具两者都能渲染
 */
function toBase64(str: string): string {
  const table = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
  const bytes: number[] = []
  for (let i = 0; i < str.length; i++) {
    const c = str.charCodeAt(i)
    if (c < 0x80) {
      bytes.push(c)
    } else if (c < 0x800) {
      bytes.push(0xc0 | (c >> 6), 0x80 | (c & 0x3f))
    } else {
      bytes.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f))
    }
  }
  let out = ''
  for (let i = 0; i < bytes.length; i += 3) {
    const b0 = bytes[i]
    const b1 = i + 1 < bytes.length ? bytes[i + 1] : -1
    const b2 = i + 2 < bytes.length ? bytes[i + 2] : -1
    out += table[b0 >> 2]
    out += table[((b0 & 3) << 4) | (b1 >= 0 ? b1 >> 4 : 0)]
    out += b1 >= 0 ? table[((b1 & 15) << 2) | (b2 >= 0 ? b2 >> 6 : 0)] : '='
    out += b2 >= 0 ? table[b2 & 63] : '='
  }
  return out
}

interface IconProps {
  name: IconName;
  /** 尺寸，单位 rpx（默认 44rpx = 网页 22px） */
  size?: number;
  /** 描边颜色（默认 #9CA3AF 灰） */
  color?: string;
  /** 填充颜色（默认 none，激活态传颜色） */
  fill?: string;
  strokeWidth?: number;
}

export default function Icon({ name, size = 44, color = '#9CA3AF', fill = 'none', strokeWidth = 2 }: IconProps) {
  const src = useMemo(() => {
    const paths = SVG_PATHS[name] || SVG_PATHS['info'];
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="${fill}" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>`;
    return `data:image/svg+xml;base64,${toBase64(svg)}`;
  }, [name, color, fill, strokeWidth]);

  return <Image src={src} style={{ width: `${size}rpx`, height: `${size}rpx` }} mode="aspectFit" />;
}
